# ------------------------------------------------------------
# 2. Download price data
# ------------------------------------------------------------

def fetch_price_data(ticker, start, end):
    """
    Downloads adjusted daily closing prices.

    SPY is used instead of ^GSPC because SPY is an investable ETF
    and adjusted prices include distributions such as dividends.
    """

    raw = yf.download(
        ticker,
        start=start,
        end=end,
        auto_adjust=True,
        progress=False,
    )

    if raw.empty:
        raise RuntimeError(
            f"No data returned for {ticker} "
            f"from {start} to {end}."
        )

    close = raw["Close"]

    # Compatibility with different yfinance versions
    if isinstance(close, pd.DataFrame):
        close = close.iloc[:, 0]

    close = close.dropna().astype(float)
    close = close.to_frame(name="Close")

    if len(close) < 2:
        raise RuntimeError("Not enough price observations.")

    return close


# ------------------------------------------------------------
# 3. Lump-sum investment
# ------------------------------------------------------------

def compute_lump_sum(df, initial_investment):
    """
    Invests the entire amount on the first available trading day.
    """

    first_price = df["Close"].iloc[0]
    shares = initial_investment / first_price

    lump_value = df["Close"] * shares

    return lump_value, shares


# ------------------------------------------------------------
# 4. DCA investment
# ------------------------------------------------------------

def compute_dca(df, monthly_contribution, n_months):
    """
    Invests the same amount on the first available trading day
    of every month.
    """

    monthly_period = df.index.to_period("M")

    purchase_dates = (
        df.groupby(monthly_period)
          .head(1)
          .index[:n_months]
    )

    if len(purchase_dates) < n_months:
        raise ValueError(
            f"Only {len(purchase_dates)} purchase months found, "
            f"but {n_months} were required."
        )

    is_purchase_day = df.index.isin(purchase_dates)

    # Number of shares purchased on each day
    shares_bought = np.where(
        is_purchase_day,
        monthly_contribution / df["Close"].to_numpy(),
        0.0,
    )

    shares_bought = pd.Series(
        shares_bought,
        index=df.index,
        name="Shares_Bought",
    )

    cumulative_shares = shares_bought.cumsum()

    dca_value = cumulative_shares * df["Close"]

    # Amount invested on each day
    invested_today = np.where(
        is_purchase_day,
        monthly_contribution,
        0.0,
    )

    invested_today = pd.Series(
        invested_today,
        index=df.index,
        name="Invested_Today",
    )

    cumulative_invested = invested_today.cumsum()

    return (
        dca_value,
        cumulative_invested,
        shares_bought,
        purchase_dates,
    )


# ------------------------------------------------------------
# 5. XIRR calculation
# ------------------------------------------------------------

def xnpv(rate, cash_flows):
    """
    Calculates the net present value of irregular cash flows.

    cash_flows must be a pandas Series:
        index = dates
        values = cash flows
    """

    dates = pd.to_datetime(cash_flows.index)
    values = cash_flows.to_numpy(dtype=float)

    days = (dates - dates[0]).days.to_numpy()

    return np.sum(
        values / (1 + rate) ** (days / 365.25)
    )


def xirr(cash_flows):
    """
    Calculates annualized return for irregular cash flows.

    Negative values represent investments.
    Positive values represent withdrawals or final portfolio value.
    """

    cash_flows = cash_flows.dropna().astype(float)

    if not (cash_flows < 0).any():
        return np.nan

    if not (cash_flows > 0).any():
        return np.nan

    def objective(rate):
        return xnpv(rate, cash_flows)

    lower_bound = -0.9999
    upper_bound = 1.0

    # Expand upper bound if necessary
    while objective(upper_bound) > 0 and upper_bound < 1_000_000:
        upper_bound *= 2

    try:
        result = brentq(
            objective,
            lower_bound,
            upper_bound,
        )
        return result

    except ValueError:
        return np.nan


# ------------------------------------------------------------
# 6. Cash-flow-adjusted daily returns
# ------------------------------------------------------------

def compute_cash_flow_adjusted_returns(
    portfolio_value,
    invested_today,
):
    """
    Calculates daily returns after adjusting for new contributions.

    Formula:

        Today's value
        -------------------------
        Yesterday's value + contribution

    This avoids treating a new contribution as investment performance.
    """

    previous_value = portfolio_value.shift(1)

    denominator = previous_value + invested_today

    adjusted_returns = portfolio_value / denominator - 1

    # The first observation has no previous portfolio value
    adjusted_returns.iloc[0] = np.nan

    return adjusted_returns


# ------------------------------------------------------------
# 7. Drawdown calculation
# ------------------------------------------------------------

def maximum_drawdown_from_returns(returns):
    """
    Calculates maximum drawdown from cash-flow-adjusted returns.
    """

    returns = returns.fillna(0.0)

    wealth_index = (1 + returns).cumprod()

    running_max = wealth_index.cummax()

    drawdown = wealth_index / running_max - 1

    return drawdown.min()


def maximum_drawdown_from_values(values):
    """
    Calculates maximum drawdown for a portfolio without
    additional cash contributions.
    """

    running_max = values.cummax()

    drawdown = values / running_max - 1

    return drawdown.min()


# ------------------------------------------------------------
# 8. Performance metrics
# ------------------------------------------------------------

def calculate_lump_sum_metrics(
    df,
    lump_value,
    initial_investment,
):
    """
    Calculates metrics for lump-sum investing.
    """

    start_date = df.index[0]
    end_date = df.index[-1]

    cash_flows = pd.Series(
        [-initial_investment, lump_value.iloc[-1]],
        index=[start_date, end_date],
        dtype=float,
    )

    annualized_return = xirr(cash_flows)

    daily_returns = lump_value.pct_change().dropna()

    volatility = (
        daily_returns.std() * np.sqrt(252)
    )

    max_drawdown = maximum_drawdown_from_values(lump_value)

    final_value = lump_value.iloc[-1]

    total_return = (
        final_value / initial_investment
    ) - 1

    return {
        "Strategy": "Lump-Sum",
        "Invested": initial_investment,
        "Final Value": final_value,
        "Profit": final_value - initial_investment,
        "Total Return (%)": total_return * 100,
        "Annualized Return (%)": annualized_return * 100,
        "Volatility (%)": volatility * 100,
        "Max Drawdown (%)": max_drawdown * 100,
    }


def calculate_dca_metrics(
    df,
    dca_value,
    cumulative_invested,
    invested_today,
    purchase_dates,
):
    """
    Calculates metrics for DCA investing.

    The final positive cash flow is the final portfolio value.
    """

    final_value = dca_value.iloc[-1]
    total_invested = cumulative_invested.iloc[-1]

    # Create negative cash flows for every contribution
    dca_cash_flows = pd.Series(
        0.0,
        index=df.index,
    )

    dca_cash_flows.loc[purchase_dates] = (
        -invested_today.loc[purchase_dates]
    )

    # Add final portfolio value as a positive cash flow
    dca_cash_flows.iloc[-1] += final_value

    annualized_return = xirr(dca_cash_flows)

    adjusted_daily_returns = (
        compute_cash_flow_adjusted_returns(
            dca_value,
            invested_today,
        )
    )

    adjusted_returns_clean = (
        adjusted_daily_returns.dropna()
    )

    volatility = (
        adjusted_returns_clean.std() * np.sqrt(252)
    )

    max_drawdown = maximum_drawdown_from_returns(
        adjusted_daily_returns
    )

    total_return = (
        final_value / total_invested
    ) - 1

    return {
        "Strategy": "DCA",
        "Invested": total_invested,
        "Final Value": final_value,
        "Profit": final_value - total_invested,
        "Total Return (%)": total_return * 100,
        "Annualized Return (%)": annualized_return * 100,
        "Volatility (%)": volatility * 100,
        "Max Drawdown (%)": max_drawdown * 100,
    }


